"""Write results/numbers.tex: one \\newcommand per number the paper may cite, each with its source.

Reads the benchmark result files of the anchorgru repository (``<src>/<dataset>.json``, the summaries the
benchmark runner wrote) and the per-split prediction files (``<src>/raw/<dataset>/n<size>_*.npz``) for the
recomputed paired SEs.

Two kinds of SE appear, and the macro names say which:
  ...SE<Arm>       the SE the benchmark reported (iid per example, or moving-block bootstrap for elec2)
  ...SEre<Arm>     the same SE recomputed here from the per-example predictions (a reproduction check)
  ...SEsplit<Arm>  SE over the 3 training splits of the per-split mean difference (training-sample noise)

Macro scheme: \\n<Dataset><Size><Arm><Metric>; sizes in roman numerals (CCL 250, D 500, M 1,000, MM 2,000,
MMMM 4,000) because LaTeX names take letters only.

Run: python3 results/make_numbers.py [--src DIR] [--out results/numbers.tex]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from paired import summarise  # noqa: E402

SRC = Path("/home/tr4m0ryp/projects/oss/anchorgru/bench/results")
DATASETS = {"synthetic": "Syn", "elec2": "Elec", "physionet2012": "Phys", "physionet2012_strongprior": "PhysStrong",
            "physionet2012_gbmprior": "PhysGbm", "physionet2012_wd10": "PhysWd"}
SIZES = {250: "CCL", 500: "D", 1000: "M", 2000: "MM", 4000: "MMMM"}
ARMS = {"prior": "Prior", "ours": "Ours", "anch_l0": "Lzero", "anch_l0.1": "Lpone", "anch_l0.3": "Lpthree",
        "anch_l1": "Lone", "anch_l3": "Lthree", "anch_l10": "Lten", "unanchored": "Unanch", "gbm_init": "Gbm",
        "abl_nocap": "NoCap", "abl_randinit": "RandInit", "abl_nogate": "NoGate", "abl_wd10_l0": "WdTen"}
METRICS = {"log_loss": ("LL", 4), "brier": ("Brier", 4), "ece": ("ECE", 3), "auc": ("AUC", 3)}
BLOCK = {"elec2": 336}
SPREAD = {"l0": "Lzero", "l0.1": "Lpone", "l0.3": "Lpthree", "l1": "Lone", "l3": "Lthree"}


class Out:
    def __init__(self):
        self.lines = ["% Generated by results/make_numbers.py; do not edit by hand.", ""]

    def add(self, name: str, value, src: str):
        self.lines.append(f"% {src}")
        self.lines.append(f"\\newcommand{{\\n{name}}}{{{value}}}")

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def f(x, d=4, sign=False):
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    return s.replace("+", "{+}").replace("-", "$-$") if sign else s


def thousands(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def per_size(o: Out, ds: str, tag: str, size: str, s: dict, src: Path):
    j = f"{ds}.json sizes[{size}]"
    sz = SIZES[int(size)]
    p = f"{tag}{sz}"
    o.add(f"{p}Ntest", thousands(s["n_test_unique"]), f"{j}.n_test_unique")
    o.add(f"{p}Nsplits", s["n_splits"], f"{j}.n_splits")
    lams = s["lam_star_per_split"]
    o.add(f"{p}Lams", ", ".join(f"{x:g}" for x in lams), f"{j}.lam_star_per_split (penalty chosen per split)")
    for arm, a in ARMS.items():
        m = s["metrics"].get(arm)
        if m is None:
            continue
        for k, (mn, d) in METRICS.items():
            o.add(f"{p}{a}{mn}", f(m[k], d), f"{j}.metrics.{arm}.{k} (mean over splits)")
        dd = s["diff_log_loss_ours_minus_arm"].get(arm)
        if dd is None:
            continue
        o.add(f"{p}D{a}", f(dd["mean"], 4, True), f"{j}.diff_log_loss_ours_minus_arm.{arm}.mean (ours - arm, nats)")
        o.add(f"{p}Dthree{a}", f(dd["mean"], 3, True), "same, 3 decimals")
        o.add(f"{p}Dabs{a}", f(abs(dd["mean"]), 3), "same, absolute, 3 decimals")
        o.add(f"{p}SE{a}", f(dd["se"], 4), f"{j}.diff_log_loss_ours_minus_arm.{arm}.se ({dd['se_method']})")
        o.add(f"{p}SEthree{a}", f(dd["se"], 3), "same, 3 decimals")
        z = dd["mean"] / dd["se"] if dd["se"] > 0 else 0.0
        o.add(f"{p}Z{a}", f(z, 1, True), "mean / reported SE")
        re = summarise(src / "raw" / ds, int(size), arm, BLOCK.get(ds))
        key = "se_block" if ds in BLOCK else "se_iid"
        how = "moving-block bootstrap, 336 rows, 2000 draws, seed 0" if ds in BLOCK else "iid sd/sqrt(n)"
        o.add(f"{p}SEre{a}", f(re[key], 4), f"raw/{ds}/n{size}_*.npz recomputed per example ({how})")
        o.add(f"{p}SEsplit{a}", f(re["se_split"], 4), f"raw/{ds}/n{size}_*.npz SE over {len(re['split_means'])} "
                                                     "split means (training-sample noise)")
    dg = s["diagnostics_train"]
    for arm in ("anch_l0", "ours"):
        if arm in dg:
            cap = sum(x["share_at_cap"] for x in dg[arm]) / len(dg[arm])
            rms = sum(x["residual_rms"] for x in dg[arm]) / len(dg[arm])
            o.add(f"{p}{ARMS[arm]}AtCap", f(100 * cap, 0), f"{j}.diagnostics_train.{arm}[].share_at_cap, mean, %")
            o.add(f"{p}{ARMS[arm]}Rms", f(rms, 2), f"{j}.diagnostics_train.{arm}[].residual_rms, mean, logit")
    o.add(f"{p}GbmRounds", f(sum(s["gbm_rounds"]) / len(s["gbm_rounds"]), 0), f"{j}.gbm_rounds, mean")
    o.add(f"{p}Seconds", f(sum(s["seconds"]) / len(s["seconds"]), 0), f"{j}.seconds, mean per split (all arms)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", type=Path, default=SRC, help="directory holding <dataset>.json and raw/")
    ap.add_argument("--out", type=Path, default=HERE / "numbers.tex")
    a = ap.parse_args()
    o = Out()
    total = 0.0
    for ds, tag in DATASETS.items():
        r = json.loads((a.src / f"{ds}.json").read_text())
        o.lines += ["", f"% ---- {ds} ----"]
        for size, s in r["sizes"].items():
            per_size(o, ds, tag, size, s, a.src)
        sp = r.get("seed_spread", {})
        for k, nm in SPREAD.items():
            if k in sp:
                o.add(f"{tag}Spread{nm}", f(sp[k]["seed_spread_p_test"], 3),
                      f"{ds}.json seed_spread.{k}.seed_spread_p_test ({sp['split']}, {sp[k]['n_seeds']} seeds)")
                o.add(f"{tag}Spread{nm}AtCap", f(100 * sp[k]["share_at_cap_train"], 0),
                      f"{ds}.json seed_spread.{k}.share_at_cap_train, %")
        o.add(f"{tag}WallMin", f(r["wall_seconds_this_call"] / 60, 1), f"{ds}.json wall_seconds_this_call / 60")
        total += r["wall_seconds_this_call"]
        st = r["settings"]
        if "bayes" in st:
            for k, (mn, d) in METRICS.items():
                o.add(f"{tag}Bayes{mn}", f(st["bayes"][k], d), f"{ds}.json settings.bayes.{k} (true probability)")
        if "test_positive_rate" in st:
            o.add(f"{tag}PosRate", f(100 * st["test_positive_rate"], 1), f"{ds}.json settings.test_positive_rate, %")
    o.lines.append("")
    o.add("WallTotalMin", f(total / 60, 0), "sum of wall_seconds_this_call over the six result files / 60")
    o.add("SweepCount", 6, "bench/common/arms.py SWEEP = (0, 0.1, 0.3, 1, 3, 10)")
    o.add("AblationCount", 4, "bench/common/arms.py ablations: no cap, random head init, no gate, wd x10 at penalty 0")
    o.add("VariantCount", 3, "bench/results/SCOPE.md variant log V1-V3")
    o.add("SeedSpreadSeeds", 5, "bench/common/runner.py _spread n_seeds")
    o.add("NetHidden", 8, "bench/common/arms.py NET hidden")
    o.add("NetCap", "2.5", "bench/common/arms.py NET cap")
    o.add("NetLr", "8\\times10^{-3}", "bench/common/arms.py NET lr")
    o.add("NetWd", "0.2", "bench/common/arms.py NET weight_decay")
    o.add("ElecOldGbmLL", "0.563 / 0.527", "bench/results/SCOPE.md cuts: first elec2 LightGBM run (12 raw lags), n 500 / 2,000")
    priv = (a.src / "PRIVATE_LINE.txt").read_text().strip()
    o.add("PrivateLine", priv, "PRIVATE_LINE.txt (the one permitted sentence on the proprietary task)")
    a.out.write_text(o.text())
    print(f"wrote {a.out} ({sum(1 for x in o.lines if x.startswith(chr(92)))} macros)")


if __name__ == "__main__":
    main()
